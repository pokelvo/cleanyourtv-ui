#!/usr/bin/env bash
# Builds CleanYourTV-UI.apk without Gradle: aapt2 -> javac -> d8 -> zipalign -> apksigner.
# Needs a JDK (17+) and the Android SDK command-line tools (build-tools 34+, platform android-34). See README.md.
set -euo pipefail
cd "$(dirname "$0")"

# --- Tools
SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
if [ -z "$SDK" ]; then
  for d in "$HOME/Library/Android/sdk" "$HOME/Android/Sdk" /opt/homebrew/share/android-commandlinetools \
           /usr/local/share/android-commandlinetools /usr/lib/android-sdk; do
    if [ -d "$d/build-tools" ]; then SDK="$d"; break; fi
  done
fi
[ -n "$SDK" ] && [ -d "$SDK/build-tools" ] || { echo "Android SDK not found. Install it and set ANDROID_HOME (see README)."; exit 1; }
# javac, d8 and apksigner are native Windows programs even when this runs under git-bash/MSYS, and they
# cannot read an MSYS '/c/Users/...' path: javac then fails with "Unable to find package java.lang in
# platform classes" and the bootclasspath separator never gets a chance to matter. Ask the shell for the
# Windows form when it can give one (the same pwd -W idiom tools/disable.sh uses).
SDK="$(cd "$SDK" && { pwd -W 2>/dev/null || pwd; })"
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
AJ="$(ls -d "$SDK"/platforms/android-*/android.jar 2>/dev/null | sort -V | tail -1 || true)"
[ -f "${AJ:-}" ] || { echo "Android platform not found. Run: sdkmanager \"platforms;android-34\""; exit 1; }
# classes.dex is added to the APK with a zip writer. zip(1) stays the first choice, so a Unix/macOS box
# keeps building exactly as before; git-bash/MSYS on Windows has no zip(1), so fall back to Python's
# zipfile in append mode, which leaves aapt2's existing entry order untouched.
ZIPPY="${PYTHON:-}"
if [ -z "$ZIPPY" ]; then ZIPPY="$(command -v python3 || command -v python || true)"; fi
if ! command -v zip >/dev/null 2>&1 && [ -z "$ZIPPY" ]; then
  echo "No zip(1) and no Python 3 to pack classes.dex. Install either (or set PYTHON)."; exit 1
fi
JAVAC="${JAVA_HOME:+$JAVA_HOME/bin/}javac"
KEYTOOL="${JAVA_HOME:+$JAVA_HOME/bin/}keytool"
command -v "$JAVAC" >/dev/null 2>&1 || { echo "JDK not found. Install JDK 17 and set JAVA_HOME."; exit 1; }

# --- Settings: config.properties -> Config.java
if [ ! -f config.properties ]; then
  cp config.example.properties config.properties
  echo "Created config.properties: add your TMDB key and your city there (optional), then build again."
fi
prop() {
  local v
  v="$(grep -E "^[[:space:]]*$1[[:space:]]*=" config.properties | tail -1 | cut -d= -f2- || true)"
  v="$(printf '%s' "$v" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' | tr -d '"\\')"
  printf '%s' "${v:-$2}"
}
number() {
  local v; v="$(prop "$1" "$2")"
  [[ "$v" =~ ^-?[0-9]+(\.[0-9]+)?$ ]] || { echo "config.properties: $1 must be a number (got \"$v\")" >&2; exit 1; }
  printf '%s' "$v"
}
LAT="$(number latitude 40.7128)"
LON="$(number longitude -74.0060)"
ASSIST=false; [ "$(prop disable_assistant false)" = "true" ] && ASSIST=true
CRYPTO=false; [ "$(prop show_crypto true)" = "true" ] && CRYPTO=true

# The update button: the GitHub repo this checkout comes from, and the last launcher-ui commits of it that this build
# already has (git log on the merge base with origin/main). The home screen compares them with GitHub's list. Empty
# outside a git clone of a GitHub repo: then the button never shows a dot.
UPDATE_REPO="$(git -C .. remote get-url origin 2>/dev/null | sed -nE 's#^.*github\.com[:/]([^/]+/[^/]+)$#\1#p' | sed 's/\.git$//' || true)"
UPDATE_BRANCH=main
UPDATE_KNOWN=""
if BASE="$(git -C .. merge-base HEAD "origin/$UPDATE_BRANCH" 2>/dev/null)"; then
  UPDATE_KNOWN="$(git -C .. log --format=%H -10 "$BASE" -- launcher-ui 2>/dev/null | cut -c1-12 | paste -sd, - || true)"
fi
[ -n "$UPDATE_KNOWN" ] || UPDATE_REPO=""
# The commit this build comes from: the NAS (nas_url) compares it with its ma-tv branch.
BUILD_ID="$(git -C .. rev-parse HEAD 2>/dev/null || true)"

rm -rf out && mkdir -p out/gen/io/cleanyourtv/ui out/classes
cat > out/gen/io/cleanyourtv/ui/Config.java <<EOF
package io.cleanyourtv.ui;

/** Generated by build.sh from config.properties: edit that file, not this one. */
final class Config {
    private Config() {}

    static final String TMDB_KEY = "$(prop tmdb_key '')";
    static final String TMDB_REGION = "$(prop tmdb_region US)";
    static final String PLEX_URL = "$(prop plex_url '')";
    static final String PLEX_TOKEN = "$(prop plex_token '')";
    static final String LIVE_TV = "$(prop live_tv '')";
    static final String JS_USER = "$(prop jointspace_user '')";
    static final String JS_PASS = "$(prop jointspace_pass '')";
    static final int SCREENSAVER_MINUTES = $(number screensaver_minutes 0);
    static final String LATITUDE = "$LAT";
    static final String LONGITUDE = "$LON";
    static final String CITY = "$(prop city '')";
    static final String LANGUAGE = "$(prop language auto)";
    static final String CURRENCY = "$(prop currency USD)";
    static final String TEMPERATURE = "$(prop temperature auto)";
    static final boolean DISABLE_ASSISTANT = $ASSIST;
    static final boolean SHOW_CRYPTO = $CRYPTO;
    static final String UPDATE_REPO = "$UPDATE_REPO";
    static final String UPDATE_BRANCH = "$UPDATE_BRANCH";
    static final String UPDATE_KNOWN = "$UPDATE_KNOWN";
    static final String BUILD_ID = "$BUILD_ID";
    static final String NAS_URL = "$(prop nas_url '')";
}
EOF

# --- Build
"$BT/aapt2" compile --dir app/res -o out/res.zip
# Network: HTTPS only, except plain HTTP to the Plex server at home (plex_url), which has no certificate on the LAN.
PLEX_HOST="$(prop plex_url '' | sed -E 's#^[a-zA-Z]+://##; s#[:/].*$##')"
mkdir -p out/netsec/xml
{
  echo '<?xml version="1.0" encoding="utf-8"?>'
  echo '<network-security-config>'
  echo '    <base-config cleartextTrafficPermitted="false" />'
  if [ -n "$PLEX_HOST" ]; then
    echo '    <domain-config cleartextTrafficPermitted="true">'
    echo "        <domain includeSubdomains=\"false\">$PLEX_HOST</domain>"
    echo '    </domain-config>'
  fi
  echo '</network-security-config>'
} > out/netsec/xml/network_security.xml
"$BT/aapt2" compile --dir out/netsec -o out/netsec.zip
# Fonts uncompressed: Android reads them straight from the APK.
"$BT/aapt2" link -o out/base.apk -I "$AJ" --manifest app/AndroidManifest.xml --java out/gen out/res.zip out/netsec.zip \
  --min-sdk-version 28 --target-sdk-version 33 -A app/assets -0 ttf
# Windows aapt2 packs assets with backslash separators ("assets/symbols\x.png") and Android
# cannot find them: the home screen loses its icons and fonts. Rename the zip entries to "/".
case "$(uname -s 2>/dev/null)" in
  MINGW*|MSYS*|CYGWIN*)
    cat > out/FixAssets.java <<'EOF'
import java.nio.file.*;
import java.util.zip.*;

class FixAssets {
    public static void main(String[] args) throws Exception {
        Path apk = Paths.get(args[0]);
        Path tmp = apk.resolveSibling(apk.getFileName() + ".fixed");
        int renamed = 0;
        try (ZipInputStream in = new ZipInputStream(Files.newInputStream(apk));
             ZipOutputStream out = new ZipOutputStream(Files.newOutputStream(tmp))) {
            for (ZipEntry e; (e = in.getNextEntry()) != null; ) {
                byte[] data = in.readAllBytes();
                String name = e.getName().replace('\\', '/');
                if (!name.equals(e.getName())) renamed++;
                ZipEntry n = new ZipEntry(name);
                if (e.getMethod() == ZipEntry.STORED) { // Android reads fonts straight from the APK
                    n.setMethod(ZipEntry.STORED);
                    n.setSize(data.length);
                    n.setCompressedSize(data.length);
                    CRC32 crc = new CRC32();
                    crc.update(data);
                    n.setCrc(crc.getValue());
                }
                out.putNextEntry(n);
                out.write(data);
                out.closeEntry();
            }
        }
        if (renamed > 0) Files.move(tmp, apk, StandardCopyOption.REPLACE_EXISTING);
        else Files.delete(tmp);
        System.out.println("FixAssets: renamed " + renamed + " asset paths in " + apk.getFileName());
    }
}
EOF
    "${JAVA_HOME:+$JAVA_HOME/bin/}java" out/FixAssets.java out/base.apk
    ;;
esac
# The bootclasspath is a two-entry list, and the separator is platform-specific: Windows javac wants
# ';' where Unix wants ':'. With the wrong one javac reads the whole thing as a single missing path
# and every lambda in the sources fails with "Unable to find method metafactory" (LambdaMetafactory
# lives in core-lambda-stubs.jar, not in android.jar). MSYS/Cygwin run the Windows javac, so they
# need ';' too.
CP_SEP=":"
case "$(uname -s)" in MINGW*|MSYS*|CYGWIN*) CP_SEP=";";; esac
"$JAVAC" -nowarn -Xlint:-options -source 8 -target 8 -bootclasspath "$AJ${CP_SEP}$BT/core-lambda-stubs.jar" -classpath "$AJ" \
  -encoding UTF-8 -d out/classes $(find app/src out/gen -name '*.java')
# d8 and apksigner ship as .bat wrappers on Windows and extensionless ones on Unix; aapt2 and
# zipalign are .exe there. Resolve each tool by what the SDK actually contains.
tool() {
  local n="$1" c
  for c in "$BT/$n" "$BT/$n.exe" "$BT/$n.bat"; do
    if [ -f "$c" ]; then printf '%s' "$c"; return; fi
  done
  printf '%s' "$BT/$n"
}
D8="$(tool d8)"
APKSIGNER="$(tool apksigner)"
"$D8" --release --min-api 28 --lib "$AJ" --output out $(find out/classes -name '*.class')
if command -v zip >/dev/null 2>&1; then
  (cd out && zip -qj base.apk classes.dex)
else
  # Python <3.7 ignores the ZipFile compression argument for write() and stores the entry instead;
  # Android reads either, so that is a size difference and nothing more.
  (cd out && "$ZIPPY" -c "import zipfile; z=zipfile.ZipFile('base.apk','a',zipfile.ZIP_DEFLATED); z.write('classes.dex','classes.dex'); z.close()")
fi
"$BT/zipalign" -f -p 4 out/base.apk out/aligned.apk

# --- Sign with your own key (created once; updates need the same key, so keep cleanyourtv-ui.keystore)
if [ ! -f cleanyourtv-ui.keystore ]; then
  "$KEYTOOL" -genkeypair -keystore cleanyourtv-ui.keystore -alias cleanyourtv-ui -keyalg RSA -keysize 2048 -validity 20000 \
    -storepass cleanyourtv-ui -keypass cleanyourtv-ui -dname "CN=CleanYourTV UI" >/dev/null 2>&1
fi
"$APKSIGNER" sign --ks cleanyourtv-ui.keystore --ks-pass pass:cleanyourtv-ui --key-pass pass:cleanyourtv-ui --out CleanYourTV-UI.apk out/aligned.apk
echo "Built CleanYourTV-UI.apk ($(du -h CleanYourTV-UI.apk | cut -f1)). Install: adb install -r CleanYourTV-UI.apk"
